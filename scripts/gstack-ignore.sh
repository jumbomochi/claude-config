#!/bin/bash
# Regenerate the gstack block in .gitignore. gstack's ./setup creates one
# wrapper dir per gstack skill in skills/; they are machine-generated, so they
# stay out of git. Rerun after bumping gstack.lock.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
GI="$ROOT/.gitignore"
BEGIN="# >>> gstack wrappers (generated by scripts/gstack-ignore.sh)"
END="# <<< gstack wrappers"

{
  awk -v b="$BEGIN" -v e="$END" '$0==b{skip=1} !skip{print} $0==e{skip=0}' "$GI"
  echo "$BEGIN"
  echo "skills/_gstack-command/"
  for f in "$ROOT"/skills/gstack/*/SKILL.md; do
    echo "skills/$(basename "$(dirname "$f")")/"
  done
  echo "$END"
} > "$GI.tmp"
mv "$GI.tmp" "$GI"
echo "gstack block in .gitignore: $(awk -v b="$BEGIN" -v e="$END" '$0==b{on=1;next} $0==e{on=0} on' "$GI" | wc -l | tr -d ' ') entries"
